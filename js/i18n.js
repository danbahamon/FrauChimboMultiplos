  const locales = { de: 'de-DE', en: 'en-GB', es: 'es-ES' };
  let lang = 'de';

  function setLang(l) {
    lang = dict[l] ? l : 'de';
    document.documentElement.lang = lang;
  }

  function t(key, vars) {
    let s = (dict[lang] && dict[lang][key]) ?? dict.de[key] ?? key;
    if (vars) s = s.replace(/\{(\w+)\}/g, (m, k) => (vars[k] !== undefined ? vars[k] : m));
    return s;
  }

  function num(n) {
    return new Intl.NumberFormat(locales[lang]).format(n);
  }

  function dec(n, digits) {
    return n.toLocaleString(locales[lang], { minimumFractionDigits: digits, maximumFractionDigits: digits });
  }

  function secs(ms) {
    return dec(ms / 1000, 3);
  }

  function list(items) {
    const strs = items.map(String);
    try {
      return new Intl.ListFormat(locales[lang], { style: 'long', type: 'conjunction' }).format(strs);
    } catch (e) {
      return strs.join(', ');
    }
  }

  return { t, num, dec, secs, list, setLang, getLang: () => lang };
